/// Computes rank points (from N down to 1) for a list of numeric values in a group of size N.
fn compute_numeric_ranks(values: &[u64], direction: Direction) -> Vec<(usize, f64)> {
    let n = values.len();
    if n == 0 {
        return Vec::new();
    }
    let mut results = Vec::with_capacity(n);
    for &val in values {
        let strictly_better_count = values
            .iter()
            .filter(|&&other| match direction {
                Direction::HigherIsBetter => other > val,
                Direction::LowerIsBetter => other < val,
            })
            .count();
        let rank_points = n.saturating_sub(strictly_better_count);
        let normalized = rank_points as f64 / n as f64;
        results.push((rank_points, normalized));
    }
    results
}

fn lookup_codec_score(codec: &str, cfg: &CodecScoringConfig) -> (f64, f64) {
    let upper = codec.trim().to_uppercase();
    let pts = cfg
        .scores
        .get(&upper)
        .copied()
        .or_else(|| {
            if upper.starts_with("WMV") {
                cfg.scores.get("WMV").copied()
            } else if upper == "AC3" {
                cfg.scores.get("AC-3").copied()
            } else if upper == "AC-3" {
                cfg.scores.get("AC3").copied()
            } else {
                None
            }
        })
        .unwrap_or(0.0);
    let max_s = cfg.max_score.max(1.0);
    let norm = (pts / max_s).clamp(0.0, 1.0);
    (pts, norm)
}

fn is_video_file(path: &Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .map(|ext| VIDEO_EXTENSIONS.contains(&ext.to_lowercase().as_str()))
        .unwrap_or(false)
}

/// Resolves `--decision-config`:
/// If not provided by the user, defaults to `decision_config.yaml` in the same directory as the `rusty_clean` binary.
/// Only throws an error if the resolved file is missing.
fn resolve_decision_config_path(explicit_path: Option<&Path>, verbose: bool, start: &Instant) -> Result<PathBuf> {
    if let Some(p) = explicit_path {
        if verbose {
            eprintln!(
                "[Verbose][+{:.3}s] Checking explicit --decision-config path: {:?}",
                start.elapsed().as_secs_f64(),
                p
            );
        }
        if !p.exists() {
            anyhow::bail!("Specified decision config file is missing: {:?}", p);
        }
        return Ok(p.to_path_buf());
    }

    let exe_path = std::env::current_exe()
        .with_context(|| "Failed to determine the path of the running rusty_clean binary")?;
    let exe_dir = exe_path
        .parent()
        .with_context(|| format!("Failed to determine parent directory of {:?}", exe_path))?;
    let default_cfg = exe_dir.join("decision_config.yaml");

    if verbose {
        eprintln!(
            "[Verbose][+{:.3}s] No --decision-config passed; resolved default config alongside binary: {:?}",
            start.elapsed().as_secs_f64(),
            default_cfg
        );
    }

    if !default_cfg.exists() {
        anyhow::bail!(
            "Default decision config file {:?} is missing (expected in the same directory as the rusty_clean binary).",
            default_cfg
        );
    }

    Ok(default_cfg)
}

/// Normalizes a directory path purely lexically or via cached canonicalization so we don't repeat slow disk syscalls
fn normalize_dir_path_lexical(path: &Path) -> PathBuf {
    let abs = if path.is_absolute() {
        path.to_path_buf()
    } else if let Ok(cwd) = std::env::current_dir() {
        cwd.join(path)
    } else {
        path.to_path_buf()
    };
    let mut cleaned = PathBuf::new();
    for comp in abs.components() {
        match comp {
            std::path::Component::CurDir => {}
            std::path::Component::ParentDir => {
                cleaned.pop();
            }
            other => cleaned.push(other.as_os_str()),
        }
    }
    cleaned
}

fn normalize_dir_path_cached(path: &Path, cache: &mut HashMap<PathBuf, PathBuf>) -> PathBuf {
    if let Some(cached) = cache.get(path) {
        return cached.clone();
    }
    let resolved = fs::canonicalize(path).unwrap_or_else(|_| normalize_dir_path_lexical(path));
    cache.insert(path.to_path_buf(), resolved.clone());
    resolved
}

#[cfg(unix)]
fn file_dev_inode(_path: &Path, meta: &fs::Metadata) -> (u64, u64) {
    (meta.dev(), meta.ino())
}

#[cfg(not(unix))]
fn file_dev_inode(path: &Path, _meta: &fs::Metadata) -> (u64, u64) {
    let canonical = fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
    let prefix_str = canonical
        .components()
        .next()
        .map(|c| c.as_os_str().to_string_lossy().to_lowercase())
        .unwrap_or_else(|| "default_vol".to_string());
    let dev_hash = blake3::hash(prefix_str.as_bytes());
    let db = dev_hash.as_bytes();
    let dev = u64::from_le_bytes([db[0], db[1], db[2], db[3], db[4], db[5], db[6], db[7]]);

    let path_norm = canonical.to_string_lossy().to_lowercase();
    let ino_hash = blake3::hash(path_norm.as_bytes());
    let ib = ino_hash.as_bytes();
    let ino = u64::from_le_bytes([ib[0], ib[1], ib[2], ib[3], ib[4], ib[5], ib[6], ib[7]]);
    (dev, ino)
}

